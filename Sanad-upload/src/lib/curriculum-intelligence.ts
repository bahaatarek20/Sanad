// =========================================================================

export interface ProgressionStep {
  title: string
  slug?: string
  stage?: number
  isAvailableOnPlatform: boolean
  categoryTitle?: string
  categorySlug?: string
  instructor?: string
}

export interface CourseProgressionInfo {
  prerequisites: ProgressionStep[]
  currentCourse: ProgressionStep
  nextCourses: ProgressionStep[]
  isFoundational: boolean // صحيح إذا كان المتن من المرحلة الأولى ولا يتطلب متطلباً سابقاً
  stage: 1 | 2 | 3
  stageName: string
  disciplineTitle: string
  disciplineSlug: string
  disciplineSequence: ProgressionStep[]
  positionInDiscipline: {
    current: number
    total: number
  }
}

/**
 * دالة ربط وتحليل متطلبات ومسار أي متن في المنصة
 * تربط المتن تلقائياً بالمتون المتوفرة فعلياً في المنصة أو تقترح المتون المعتمدة
 */
export function resolveCourseProgression(
  course: MatnCourse,
  allCourses: MatnCourse[] = []
): CourseProgressionInfo {
  const normCurrentTitle = normalizeArabicText(course.title)

  // 1. استخراج المتطلبات السابقة
  let prereqTitles: string[] = []
  if (Array.isArray(course.prerequisites) && course.prerequisites.length > 0) {
    prereqTitles = course.prerequisites
  } else {
    const analysis = analyzeMatnStage(course.title, course.categorySlug, course.stage, course.author, course.description)
    prereqTitles = analysis.pedagogicalPrerequisites || []
  }

  // مطابقة كل متطلب مع المتون المتاحة بالمنصة
  const resolvedPrerequisites: ProgressionStep[] = prereqTitles.map((title) => {
    const norm = normalizeArabicText(title)
    const match = allCourses.find((c) => {
      if (c.slug === course.slug) return false
      const cNorm = normalizeArabicText(c.title)
      return (
        cNorm === norm ||
        cNorm.includes(norm) ||
        norm.includes(cNorm) ||
        c.slug === title
      )
    })

    if (match) {
      return {
        title: match.title,
        slug: match.slug,
        stage: (match.stage as 1 | 2 | 3) || 1,
        isAvailableOnPlatform: true,
        categoryTitle: match.category,
        categorySlug: match.categorySlug,
        instructor: match.instructor,
      }
    }

    return {
      title,
      isAvailableOnPlatform: false,
    }
  })

  // 2. استخراج المتون التالية
  let nextTitles: string[] = []
  if (Array.isArray(course.nextCourses) && course.nextCourses.length > 0) {
    nextTitles = course.nextCourses
  } else {
    // نبحث أولاً في متون المنصة المتاحة عمن يعتبر هذا المتن متطلباً له
    const directFollowers = allCourses.filter((c) => {
      if (c.slug === course.slug) return false
      if (Array.isArray(c.prerequisites) && c.prerequisites.length > 0) {
        return c.prerequisites.some((p) => {
          const pNorm = normalizeArabicText(p)
          return (
            pNorm === normCurrentTitle ||
            normCurrentTitle.includes(pNorm) ||
            pNorm.includes(normCurrentTitle) ||
            p === course.slug
          )
        })
      }
      return false
    })

    if (directFollowers.length > 0) {
      nextTitles = directFollowers.map((f) => f.title)
    } else {
      const analysis = analyzeMatnStage(course.title, course.categorySlug, course.stage, course.author, course.description)
      nextTitles = analysis.suggestedNextCourses || []
    }
  }

  const resolvedNextCourses: ProgressionStep[] = nextTitles.map((title) => {
    const norm = normalizeArabicText(title)
    const match = allCourses.find((c) => {
      if (c.slug === course.slug) return false
      const cNorm = normalizeArabicText(c.title)
      return (
        cNorm === norm ||
        cNorm.includes(norm) ||
        norm.includes(cNorm) ||
        c.slug === title
      )
    })

    if (match) {
      return {
        title: match.title,
        slug: match.slug,
        stage: (match.stage as 1 | 2 | 3) || 2,
        isAvailableOnPlatform: true,
        categoryTitle: match.category,
        categorySlug: match.categorySlug,
        instructor: match.instructor,
      }
    }

    return {
      title,
      isAvailableOnPlatform: false,
    }
  })

  // 3. تسلسل الفن الكامل داخل المنصة
  const disciplineCourses = allCourses
    .filter((c) => c.categorySlug === course.categorySlug)
    .sort((a, b) => {
      const stageA = a.stage || 1
      const stageB = b.stage || 1
      if (stageA !== stageB) return stageA - stageB
      return (a.totalLessons || 0) - (b.totalLessons || 0)
    })

  const disciplineSequence: ProgressionStep[] = disciplineCourses.map((c) => ({
    title: c.title,
    slug: c.slug,
    stage: (c.stage as 1 | 2 | 3) || 1,
    isAvailableOnPlatform: true,
    categoryTitle: c.category,
    categorySlug: c.categorySlug,
    instructor: c.instructor,
  }))

  const currentIndex = disciplineSequence.findIndex((s) => s.slug === course.slug)
  const currentPos = currentIndex >= 0 ? currentIndex + 1 : 1

  const stage = (course.stage as 1 | 2 | 3) || 1
  const stageNames: Record<1 | 2 | 3, string> = {
    1: 'المرحلة 1: تأسيس وتأصيل أولي',
    2: 'المرحلة 2: بناء وترسيخ منهجي',
    3: 'المرحلة 3: تمكن ورسوخ تخصصي',
  }

  return {
    prerequisites: resolvedPrerequisites,
    currentCourse: {
      title: course.title,
      slug: course.slug,
      stage,
      isAvailableOnPlatform: true,
      categoryTitle: course.category,
      categorySlug: course.categorySlug,
      instructor: course.instructor,
    },
    nextCourses: resolvedNextCourses,
    isFoundational: stage === 1 && resolvedPrerequisites.length === 0,
    stage,
    stageName: stageNames[stage],
    disciplineTitle: course.category,
    disciplineSlug: course.categorySlug,
    disciplineSequence,
    positionInDiscipline: {
      current: currentPos,
      total: Math.max(1, disciplineSequence.length),
    },
  }
}
