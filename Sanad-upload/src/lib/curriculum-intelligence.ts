function generateScienceSlug(name: string): string {
  const norm = normalizeArabicText(name)
  if (norm.includes('اصول الفقه')) return 'usul-al-fiqh'
  if (norm.includes('قواعد فقهية')) return 'fiqh-rules'
  if (norm.includes('حديث') || norm.includes('مصطلح')) return 'hadith'
  if (norm.includes('عقيدة') || norm.includes('توحيد')) return 'aqeedah'
  if (norm.includes('فقه')) return 'fiqh'
  if (norm.includes('نحو') || norm.includes('لغة') || norm.includes('صرف') || norm.includes('بلاغة')) return 'arabic-language'
  if (norm.includes('تفسير') || norm.includes('قران')) return 'quran-sciences'
  if (norm.includes('سيرة') || norm.includes('تاريخ')) return 'seerah-history'
  if (norm.includes('اداب') || norm.includes('اخلاق')) return 'manners'
  if (norm.includes('منطق')) return 'logic-philosophy'
  if (norm.includes('فرائض') || norm.includes('مواريث')) return 'faraid-inheritance'
  if (norm.includes('مقاصد')) return 'maqasid-shariah'
  if (norm.includes('مقارن')) return 'comparative-studies'
  return 'science-' + Math.random().toString(36).substring(2, 7)
}

