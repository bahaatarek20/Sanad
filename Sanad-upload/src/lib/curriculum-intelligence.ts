/**
 * تنظيف وتطبيع النص العربي لمقارنة دقيقة وغير حساسة للتشكيل أو الهمزات
 */
export function normalizeArabicText(text: string): string {
  if (!text) return ''
  return text
    // إزالة التشكيل والتنوين والشدات
    .replace(/[\u064B-\u065F\u0670]/g, '')
    // توحيد الهمزات
    .replace(/[إأآا]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    // إزالة التطويل (الكشيدة)
    .replace(/\u0640/g, '')
    // إزالة علامات الترقيم والأقواس
    .replace(/[«»""''()\[\]{}،,:;.؟?!-]/g, ' ')
    // توحيد المسافات
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase()
}

/**
 * توليد معرّف لاتيني (Slug) أنيق ومطابق لقواعد السيو من العنوان
 */
export function generateSmartSlug(text: string): string {
  const norm = normalizeArabicText(text)
  // قاموس تعريب سريع لأشهر المصطلحات
  const dictionary: Record<string, string> = {
    'الاصول الثلاثة': 'three-principles',
    'القواعد الاربع': 'four-principles',
    'الاربعين النووية': '40-hadith-nawawi',
    'الاجرومية': 'al-ajrumiyyah',
    'البيقونية': 'al-bayquniyyah',
    'زاد المستقنع': 'zad-al-mustaqna',
    'بلوغ المرام': 'bulugh-al-maram',
    'نخبة الفكر': 'nukhbat-al-fikar',
    'كتاب التوحيد': 'kitab-al-tawhid',
    'العقيدة الواسطية': 'al-aqeedah-al-wasitiyyah',
    'العقيدة الطحاوية': 'al-aqeedah-al-tahawiyyah',
    'الورقات': 'al-waraqat',
    'حلية طالب العلم': 'hilyat-talib-al-ilm',
    'قطر الندى': 'qatr-al-nada',
    'الفية ابن مالك': 'alfiyyat-ibn-malik',
    'بداية المتفقه': 'bidayat-al-mutafaqqih',
    'جمع الجوامع': 'jam-al-jawami',
    'مراقي السعود': 'maraqi-al-suud',
    'رفع الملام': 'raf-al-malam',
    'المغني': 'al-mughni',
  }

  for (const [key, val] of Object.entries(dictionary)) {
    if (norm.includes(normalizeArabicText(key))) {
      return val
    }
  }

  // تحويل ناعم إن لم يتطابق
  return 'matn-' + Math.random().toString(36).substring(2, 8)
}

/**
 * البحث في قاعدة المتون المعتمدة (Canonical Database)
 */
export function findCanonicalMatn(title: string): CanonicalMatn | undefined {
  if (!title || title.trim().length < 2) return undefined
  const clean = normalizeArabicText(title)

  return CANONICAL_MATN_DATABASE.find((item) => {
    const cleanCanonical = normalizeArabicText(item.canonicalTitle)
    if (clean.includes(cleanCanonical) || cleanCanonical.includes(clean)) {
      return true
    }
    return item.aliases.some((alias) => {
      const cleanAlias = normalizeArabicText(alias)
      return clean.includes(cleanAlias) || cleanAlias.includes(clean)
    })
  })
}

