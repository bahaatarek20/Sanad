/**
 * استخراج بيانات المتن الحالي والمراجع المعتمدة لتغذية الذكاء الاصطناعي بالسياق الدقيق (RAG Context)
 */
export function resolveCourseScholarlyContext(
  courseTitle?: string,
  categoryTitle?: string,
  question?: string
): {
  matchedCourse: MatnCourse | null
  relevantEntries: ScholarlyKnowledgeEntry[]
  authoritativeSources: string[]
  ragContextBlock: string
} {
  const qNorm = (question || '').toLowerCase().trim()
  const cTitleNorm = (courseTitle || '').toLowerCase().trim()

  // 1. البحث عن المتن المطابق في قائمة متون المنصة
  const matchedCourse =
    ALL_COURSES.find(
      (c) =>
        (cTitleNorm && (c.title.toLowerCase().includes(cTitleNorm) || cTitleNorm.includes(c.title.toLowerCase()))) ||
        (qNorm && qNorm.includes(c.title.toLowerCase()))
    ) || null

  const catSlug = matchedCourse?.categorySlug || inferCategorySlug(cTitleNorm, categoryTitle || '', qNorm)
  const authoritativeSources =
    CATEGORY_AUTHORITATIVE_SOURCES[catSlug] || CATEGORY_AUTHORITATIVE_SOURCES.fiqh

  // 2. البحث عن المداخل الموسوعية وثيقة الصلة بالسؤال
  const relevantEntries = SANAD_SCHOLARLY_ENCYCLOPEDIA.filter((entry) =>
    entry.keywords.some((kw) => qNorm.includes(kw.toLowerCase()))
  )

  const courseInfoLines = matchedCourse
    ? [
        `- اسم المتن المقرر في منصة سَنَد: «${matchedCourse.title}»`,
        matchedCourse.author ? `- مؤلف المتن: ${matchedCourse.author}` : '',
        matchedCourse.instructor ? `- الشارح المعتمد في المنصة: ${matchedCourse.instructor}` : '',
        `- الفن الشرعي: ${matchedCourse.category} (المرحلة التأصيلية: ${matchedCourse.stage || 1})`,
        `- نبذة المتن: ${matchedCourse.description}`,
      ]
        .filter(Boolean)
        .join('\n')
    : `- السياق العلمي: ${courseTitle || 'طلب العلم الشرعي والتأصيل المنهجي'} (${categoryTitle || 'العلوم الشرعية'})`

  const ragSnippets =
    relevantEntries.length > 0
      ? `\n\n[مادة علمية تأصيلية محررة من قاعدة معرفة سَنَد للاستئناس بها في التحرير]:\n` +
        relevantEntries
          .map(
            (e) =>
              `• ${e.title}:\n${e.answer}\nالمصادر المعتمدة لهذه المسألة: ${e.sources.join(' | ')}`
          )
          .join('\n\n')
      : ''

  const ragContextBlock = `
${courseInfoLines}
- أهم المصادر والمراجع المعتمدة في هذا الفن على منصة سَنَد:
  ${authoritativeSources.map((s, idx) => `${idx + 1}. ${s}`).join('\n  ')}${ragSnippets}
`.trim()

  return {
    matchedCourse,
    relevantEntries,
    authoritativeSources,
    ragContextBlock,
  }
}

function inferCategorySlug(courseTitle: string, categoryTitle: string, question: string): string {
  const combined = `${courseTitle} ${categoryTitle} ${question}`.toLowerCase()
  if (combined.includes('نحو') || combined.includes('آجروم') || combined.includes('أجروم') || combined.includes('إعراب') || combined.includes('اعراب') || combined.includes('صرف') || combined.includes('بلاغة')) {
    return 'arabic-language'
  }
  if (combined.includes('عقيد') || combined.includes('توحيد') || combined.includes('واسطي') || combined.includes('أصول الثلاث') || combined.includes('قواعد المثلى') || combined.includes('إيمان')) {
    return 'aqeedah'
  }
  if (combined.includes('حديث') || combined.includes('نووي') || combined.includes('نخبة') || combined.includes('مصطلح') || combined.includes('إسناد')) {
    return 'hadith'
  }
  if (combined.includes('أصول الفقه') || combined.includes('اصول الفقه') || combined.includes('ورقات') || combined.includes('حكم تكليفي')) {
    return 'usul-al-fiqh'
  }
  if (combined.includes('قواعد فقه') || combined.includes('الأمور بمقاصدها') || combined.includes('اليقين لا يزول')) {
    return 'fiqh-rules'
  }
  if (combined.includes('حلية') || combined.includes('آداب') || combined.includes('تعظيم العلم')) {
    return 'manners'
  }
  if (combined.includes('سيرة') || combined.includes('شمائل') || combined.includes('تاريخ') || combined.includes('ميئية') || combined.includes('منيرة')) {
    return 'seerah-history'
  }
  if (combined.includes('قرآن') || combined.includes('تفسير') || combined.includes('مكي') || combined.includes('مدني')) {
    return 'quran-sciences'
  }
  return 'fiqh'
}
