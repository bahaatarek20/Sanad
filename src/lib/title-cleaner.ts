/**
 * تنظيف نصوص وعناوين الفيديوهات والمجالس في منصة سَنَد:
 * 1. إزالة أي دلالات لجودة ودقة الفيديو نهائياً (مثل 360p, 720p, 1080p, 4K, HD, FHD) سواء كانت داخل أقواس أو بدونها.
 * 2. إزالة السابقة التلقائية المكررة "المجلس X: " أو "الدرس X: " إذا كان العنوان يحتوي على نص الفيديو الفعلي ليبقى النص كما هو مكتوب فقط.
 * 3. إزالة امتدادات ملفات الفيديو (.mp4, .mkv, إلخ) والشرطات السفلية.
 */
export function cleanVideoTitle(raw: string | undefined | null): string {
  if (!raw || typeof raw !== 'string') return ''

  let text = raw.trim()

  // 1. حذف امتدادات الفيديو الشائعة
  text = text.replace(/\.(mp4|mkv|avi|mov|webm|wmv|flv|m4v|ts|3gp|ogv|ogg|mpg|mpeg)$/i, '')

  // 2. استبدال الشرطات السفلية المتتالية بمسافات
  text = text.replace(/_+/g, ' ')

  // 3. حذف كافة دلالات جودة ودقة الفيديو (بأقواس أو بدون، وبأي حالة أحرف)
  // يغطي: (360p), (360P), (720p), [1080p], 360P, 480p, 720P, 1080P, 1440p, 2160p, 4K, 2K, FHD, HD, إلخ
  // أ) الأرقام الدالة على الجودة داخل أقواس حتى بدون حرف P (مثل (360) أو [720])
  text = text.replace(/[\(\[\{]\s*(?:144|240|360|480|720|1080|1440|2160)\s*(?:[pPب]|fps)?\s*[\)\]\}]/gi, '')

  // ب) الجودة مع حرف p/P/ب سواء داخل أقواس أو بدونها، وبمسافة أو بدون (مثل 360p, 360 p, 360P)
  text = text.replace(/[\(\[\{]?\s*(?:144|240|360|480|720|1080|1440|2160)\s*[pPب]\s*[\)\]\}]?/gi, '')

  // ج) دقة 4K, 2K, 8K, FHD, UHD, QHD
  text = text.replace(/[\(\[\{]?\s*(?:4[kK]|2[kK]|8[kK]|FHD|UHD|QHD)\s*[\)\]\}]?/gi, '')

  // د) معالجة HD و SD المنفصلة
  text = text.replace(/[\(\[\{]\s*(?:HD|SD)\s*[\)\]\}]/gi, '')

  // هـ) دلالات الإطارات مثل 60fps
  text = text.replace(/\b\d+\s*fps\b/gi, '')

  // و) حذف نصوص الجودة الصريحة بالعربية (مثل: جودة 360, دقة عالية, جودة عالية)
  text = text.replace(/[\(\[\{]?\s*(?:جودة|دقة)\s*(?:عالية|متوسطة|منخفضة|\d+\s*[pPب]?)[\)\]\}]?/gi, '')

  // ز) حذف الأقواس الفارغة الناتجة عن إزالة الجودة
  text = text.replace(/[\(\[\{]\s*[\)\]\}]/g, '')

  // ح) حذف أي قوس أو رمز فتح عالق في نهاية النص بدون إغلاق مثل ( أو [
  text = text.replace(/[\(\[\{]\s*$/g, '')

  // ط) تنظيف المسافات المزدوجة
  text = text.replace(/\s+/g, ' ').trim()

  // 4. حذف السابقة التلقائية المكررة مثل "المجلس 1: " أو "المجلس رقم 1: " أو "الدرس 1 - "
  // بشرط أن يتبقى نص فعلي بعد الحذف (حتى لا يصبح العنوان فارغاً إذا كان المتن كله اسمه "المجلس 1")
  const prefixRegex = /^(?:المجلس|الدرس|مجلس|درس|حلقة)(?:\s*رقم)?\s*\d+[\s:.-]+(.+)$/i
  const prefixMatch = text.match(prefixRegex)
  if (prefixMatch && prefixMatch[1] && prefixMatch[1].trim().length > 0) {
    text = prefixMatch[1].trim()
  }

  // 5. تنظيف أي علامات ترقيم أو أقواس مفتوحة عالقة في البداية أو النهاية (مثل - أو : أو . أو ()
  text = text.replace(/^[\s\-_:.]+|[\s\-_:.]+|[\(\[\{]\s*$/g, '').trim()

  return text
}

/**
 * تنظيف وصف المجلس من دلالات الجودة وامتدادات الملفات والأقواس العالقة
 */
export function cleanEpisodeDescription(raw: string | undefined | null): string {
  if (!raw || typeof raw !== 'string') return ''

  let desc = raw.trim()

  // حذف امتدادات الفيديو
  desc = desc.replace(/\.(mp4|mkv|avi|mov|webm|wmv|flv|m4v|ts|3gp|ogv|ogg|mpg|mpeg)/gi, '')

  // حذف دلالات الجودة والأرقام الخاصة بها
  desc = desc
    .replace(/[\(\[\{]\s*(?:144|240|360|480|720|1080|1440|2160)\s*(?:[pPب]|fps)?\s*[\)\]\}]/gi, '')
    .replace(/[\(\[\{]?\s*(?:144|240|360|480|720|1080|1440|2160)\s*[pPب]\s*[\)\]\}]?/gi, '')
    .replace(/[\(\[\{]?\s*(?:4[kK]|2[kK]|8[kK]|FHD|UHD|QHD)\s*[\)\]\}]?/gi, '')
    .replace(/[\(\[\{]\s*(?:HD|SD)\s*[\)\]\}]/gi, '')
    .replace(/\b\d+\s*fps\b/gi, '')
    .replace(/[\(\[\{]?\s*(?:جودة|دقة)\s*(?:عالية|متوسطة|منخفضة|\d+\s*[pPب]?)[\)\]\}]?/gi, '')
    .replace(/[\(\[\{]\s*[\)\]\}]/g, '')
    // حذف أي قوس مفتوح عالق في نهاية الوصف (مثل علامة ( في الصورة)
    .replace(/[\(\[\{]\s*$/g, '')
    .replace(/\s+/g, ' ')
    .trim()

  return desc
}
