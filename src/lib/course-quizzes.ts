export function getCourseQuiz(course: MatnCourse): QuizQuestion[] {
  if (SPECIFIC_COURSE_QUIZZES[course.slug]) {
    return SPECIFIC_COURSE_QUIZZES[course.slug]
  }
  return getGenericDisciplineQuiz(course)
}

/**
 * تصحيح إجابات الطالب وحساب النتيجة ونسبة الاجتياز (حد النجاح 80%)
 */
export function gradeCourseQuiz(
  questions: QuizQuestion[],
  selectedAnswers: (number | null)[]
): QuizResult {
  let correctCount = 0
  const totalCount = questions.length

  const details = questions.map((q, idx) => {
    const userAns = selectedAnswers[idx] ?? -1
    const isCorrect = userAns === q.correctIndex
    if (isCorrect) correctCount++

    return {
      question: q.question,
      userAnswer: userAns,
      correctAnswer: q.correctIndex,
      isCorrect,
      explanation: q.explanation,
    }
  })

  const score = Math.round((correctCount / totalCount) * 100)
  const passed = score >= 80 // 80% على الأقل (أي 4 من 5 صحيحة)

  return {
    score,
    passed,
    correctCount,
    totalCount,
    details,
  }
}
